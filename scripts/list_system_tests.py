#!/usr/bin/env python3
"""Write the system test catalogue from the test code itself (Part 5, deliverable 4).

    python scripts/list_system_tests.py            # print it
    python scripts/list_system_tests.py --write    # update docs/testing/system-test-catalogue.md

Reading the tests (not a hand-kept list) means the catalogue cannot fall out of
date (Priya, Call 5). tests/test_project_process.py fails if it does.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TESTS = ROOT / "tests" / "system"
OUTPUT = ROOT / "docs" / "testing" / "system-test-catalogue.md"

HEADER = """# System test catalogue (generated)

Generated by `python scripts/list_system_tests.py --write` from `tests/system/`. Do not edit by hand.
Run every case with `python scripts/run_system_tests.py` (or double-click `run-system-tests.cmd`).

**Kind:** black-box = designed from the requirements and Call 5 only; white-box = designed from knowing the code.
**Runs:** how many times the case runs (parametrized variants count separately in the report).
"""


def _marker(decorator: ast.expr) -> tuple[str, ast.Call | None]:
    call = decorator if isinstance(decorator, ast.Call) else None
    node = call.func if call else decorator
    parts = []
    while isinstance(node, ast.Attribute):
        parts.append(node.attr)
        node = node.value
    return ".".join(reversed(parts)), call


def _module_markers(tree: ast.Module) -> set[str]:
    names: set[str] = set()
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "pytestmark" for t in node.targets):
            for item in ast.walk(node.value):
                if isinstance(item, ast.Attribute):
                    names.add(item.attr)
    return names


def cases() -> list[dict]:
    rows = []
    for path in sorted(TESTS.glob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        module_marks = _module_markers(tree)
        for node in tree.body:
            if not isinstance(node, ast.FunctionDef) or not node.name.startswith("test_"):
                continue
            requirements: list[str] = []
            runs = 1
            whitebox = "whitebox" in module_marks
            for decorator in node.decorator_list:
                name, call = _marker(decorator)
                if name.endswith("requirement") and call:
                    requirements += [a.value for a in call.args if isinstance(a, ast.Constant)]
                elif name.endswith("parametrize") and call and len(call.args) > 1:
                    values = call.args[1]
                    if isinstance(values, (ast.List, ast.Tuple)):
                        runs *= len(values.elts)
                elif name.endswith("whitebox"):
                    whitebox = True
            doc = (ast.get_docstring(node) or "").strip().splitlines()
            title = doc[0] if doc else node.name
            case_id, _, text = title.partition(" ")
            rows.append(
                {
                    "id": case_id,
                    "title": text,
                    "kind": "white-box" if whitebox else "black-box",
                    "requirements": ", ".join(requirements),
                    "runs": runs,
                    "where": f"{path.name}::{node.name}",
                }
            )
    return sorted(rows, key=lambda r: int(r["id"].removeprefix("ST-")) if r["id"].startswith("ST-") else 999)


def render() -> str:
    rows = cases()
    black = sum(1 for r in rows if r["kind"] == "black-box")
    lines = [
        HEADER,
        f"**{len(rows)} test cases, {sum(r['runs'] for r in rows)} runs** "
        f"({black} black-box cases, {len(rows) - black} white-box cases).\n",
        "| ID | Test case (expected result) | Kind | Requirements | Runs | Code |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        title = r["title"].replace("|", "\\|")
        lines.append(
            f"| {r['id']} | {title} | {r['kind']} | {r['requirements']} | {r['runs']} | `{r['where']}` |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help=f"write {OUTPUT.relative_to(ROOT)}")
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUTPUT.relative_to(ROOT)}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
